// Map every CO (listening) question's audio URL to its cached Whisper transcript
// and emit src/data/transcripts.js for the app to read.
//
// Transcript cache files live in tools/transcripts/ and are keyed by the same
// scheme verify_audio.py uses: "{YYYY-MM}__{filename}.{model}.txt".
// We prefer the most accurate model available per clip: medium > plain > small.
//
// Run: node tools/build-transcripts.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { pathToFileURL } from 'url';
import { join } from 'path';

const root = process.cwd();
const dataDir = join(root, 'src', 'data');
const transDir = join(root, 'tools', 'transcripts');

// Replicates verify_audio.py cache_name(url).
function cacheName(url) {
  const base = decodeURIComponent(url.split('/').pop()).replace(/[^A-Za-z0-9._-]/g, '_');
  const folder = url.includes('/uploads/')
    ? url.split('/uploads/')[1].split('/').slice(0, -1).join('-')
    : 'x';
  return `${folder}__${base}`;
}

function bestTranscript(url) {
  const stem = join(transDir, cacheName(url));
  for (const suffix of ['.medium.txt', '.txt', '.small.txt']) {
    const p = stem + suffix;
    if (existsSync(p)) {
      const text = readFileSync(p, 'utf-8').trim();
      if (text) return text;
    }
  }
  return null;
}

// Collect every CO data file: questions.js (test 1) + questions-test{N}.js.
const files = readdirSync(dataDir).filter(f => /^questions(-test\d+)?\.js$/.test(f));

const map = {};
let total = 0;
const missing = [];
for (const file of files) {
  const testNum = file === 'questions.js' ? 1 : parseInt(file.match(/test(\d+)/)[1], 10);
  const mod = await import(pathToFileURL(join(dataDir, file)).href);
  const arr = Object.values(mod).find(v => Array.isArray(v) && v[0] && 'id' in v[0]);
  for (const q of arr) {
    if (!q.audio) continue;
    total += 1;
    const text = bestTranscript(q.audio);
    if (text) {
      map[q.audio] = text;
    } else {
      missing.push(`T${testNum}Q${q.id}`);
    }
  }
}

const header =
  '// AUTO-GENERATED by tools/build-transcripts.mjs - do not edit by hand.\n' +
  '// Maps each listening clip URL to its French transcript (faster-whisper).\n';
writeFileSync(
  join(dataDir, 'transcripts.js'),
  header + 'export const transcripts = ' + JSON.stringify(map, null, 0) + ';\n',
  'utf-8',
);

const have = Object.keys(map).length;
console.log(`Transcripts: ${have}/${total} clips mapped (${missing.length} missing).`);
if (missing.length) {
  console.log('Missing keys:', missing.join(', '));
}
